# ── Cell creator (Gemini text LLM) ─────────────────────────────────────

CELL_CREATOR_SYSTEM = """\
You write pose descriptions for an AI image generator that will produce a
2x2 sprite sheet — 4 animation frames in a single image. All 4 descriptions
are sent TOGETHER in one prompt, so you CAN reference relationships between
cells (e.g. 'mirror of Cell 1 with opposite limbs').

HOW THE IMAGE GENERATOR WORKS:
- It is best at varying the overall SILHOUETTE SHAPE between cells
- It struggles with 'left leg' vs 'right leg' in side view — these are
  ambiguous. Instead use: 'the leading leg' (toward right edge), 'the
  trailing leg' (toward left edge), 'the OTHER leg', or describe the
  silhouette shape ('legs wide apart' vs 'legs close together')
- It sometimes flips the character direction — explicitly state 'facing
  right' and 'toward the right edge' in EVERY cell description
- It sometimes makes all 4 cells look the same — you must describe what
  is VISUALLY DIFFERENT about each cell's silhouette

YOUR TASK:
1. Determine the movement type from the character's body plan
2. Write 4 pose descriptions that form a looping cycle
3. Write a frame_pattern that summarizes the visual contrast between frames
   (this gets inserted into the consistency rules the image generator sees)

POSE DESCRIPTION RULES:
- Describe the BODY HEIGHT in each frame (low/compressed vs tall/stretched)
- Describe the SILHOUETTE WIDTH (wide/spread vs narrow/compact)
- Use screen-space directions: 'toward the right edge' = forward,
  'toward the left edge' = backward
- NEVER say 'left leg' or 'right leg' — say 'leading leg', 'trailing leg',
  'the OTHER leg', or describe the shape
- State relationships: 'same wide stride as Cell 1 but the OTHER leg leads'
- Mention follow-through elements (capes trailing, tentacles dragging, etc)
- 2-3 sentences per cell
- Do NOT describe color, texture, or art style — only the pose

FRAME PATTERN EXAMPLES:
- Walk: 'Cells 1 and 3 show wide strides (legs apart, body low). Cells 2
  and 4 show compact passing poses (legs together, body tall).'
- Bounce: 'Cells 1 and 3 show squashed flat shapes (wide, low). Cells 2
  and 4 show stretched tall shapes (narrow, high).'
- Float: 'The body rises and falls across cells. Trailing elements change
  angle with each position.'

Output JSON only:
{
  "animation_type": "walk|bounce|slither|float|hop|crawl|etc",
  "animation_description": "2-3 sentences explaining the full motion cycle",
  "frame_pattern": "1-2 sentences describing the visual contrast pattern",
  "cells": {"1": "...", "2": "...", "3": "...", "4": "..."}
}"""


def generate_cells(desc: str) -> dict:
    from google import genai
    from google.genai import types

    client = genai.Client(api_key=os.getenv("GOOGLE_API_KEY"))
    response = client.models.generate_content(
        model=TEXT_MODEL,
        contents=f"Character: {desc}",
        config=types.GenerateContentConfig(
            system_instruction=CELL_CREATOR_SYSTEM,
            temperature=0.7,
            response_mime_type="application/json",
        ),
    )
    text = response.text.strip()
    text = re.sub(r",\s*([}\]])", r"\1", text)
    return json.loads(text)


# ── Template ───────────────────────────────────────────────────────────


def make_template_2x2() -> bytes:
    size, grid, cell = 1024, 2, 512
    img = Image.new("RGB", (size, size), "#1a1a1a")
    draw = ImageDraw.Draw(img)
    lc = "#ff0000"
    draw.line([(cell, 0), (cell, size - 1)], fill=lc, width=2)
    draw.line([(0, cell), (size - 1, cell)], fill=lc, width=2)
    draw.rectangle([0, 0, size - 1, size - 1], outline=lc, width=2)
    font = ImageFont.load_default(size=48)
    for row in range(grid):
        for col in range(grid):
            num = row * grid + col + 1
            cx, cy = col * cell + cell // 2, row * cell + cell // 2
            r = 40
            draw.ellipse([cx - r, cy - r, cx + r, cy + r],
                         fill="#fff", outline=lc, width=2)
            label = str(num)
            bbox = draw.textbbox((0, 0), label, font=font)
            tw = bbox[2] - bbox[0]
            draw.text((cx - tw // 2, cy - bbox[1] // 2 - bbox[1]),
                      label, fill="#000", font=font)
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


# ── Image generation (FLUX via SGLang) ─────────────────────────────────


def build_prompt(appearance: str, anim_data: dict) -> str:
    anim_type = anim_data.get("animation_type", "animation")
    anim_desc = anim_data.get("animation_description", "")
    cells = anim_data.get("cells", {})
    frame_pattern = anim_data.get("frame_pattern", "")
    pattern_line = f" {frame_pattern}" if frame_pattern else ""

    return (
        f"A sprite sheet for a 2D video game. A 2x2 grid with 4 equal cells "
        f"separated by thin red lines on a dark background. Each cell contains "
        f"one frame of a {anim_type} cycle animation. The character is shown in "
        f"side view facing right, moving toward the right edge. Mixed media "
        f"collage style paper cutout art, flat lighting, clean edges.\n\n"

        f"CHARACTER: {appearance}\n\n"

        f"Cell 1 (top-left): {cells.get('1', '')}\n\n"
        f"Cell 2 (top-right): {cells.get('2', '')}\n\n"
        f"Cell 3 (bottom-left): {cells.get('3', '')}\n\n"
        f"Cell 4 (bottom-right): {cells.get('4', '')}\n\n"

        f"CRITICAL RULES:\n"
        f"- The character faces toward the RIGHT edge in ALL FOUR cells. "
        f"No cell shows the character facing left.\n"
        f"- Every cell shows a VISIBLY DIFFERENT pose.{pattern_line} "
        f"If two cells look the same, the animation fails.\n"
        f"- The character looks IDENTICAL in all cells — same proportions, "
        f"colors, art style. Only the pose changes.\n"
        f"- Full body visible in every cell, centered. Flat solid dark "
        f"background. No text, no labels, no watermarks."
    )


def generate_sheet(template_bytes: bytes, prompt: str) -> bytes:
    resp = httpx.post(
        f"{FLUX_URL}/v1/images/edits",
        files={"image": ("template.png", template_bytes, "image/png")},
        data={
            "prompt": prompt,
            "size": "1024x1024",
            "response_format": "b64_json",
            "num_inference_steps": "30",
        },
        timeout=120,
    )
    resp.raise_for_status()
    return base64.b64decode(resp.json()["data"][0]["b64_json"])


# ── Bg removal + processing ───────────────────────────────────────────

_bg_cache: dict[str, object] = {}


def _remove_bg(image_bytes: bytes) -> bytes:
    try:
        import torch
        from torchvision import transforms
        from transformers import AutoModelForImageSegmentation

        if "model" not in _bg_cache:
            device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
            model = AutoModelForImageSegmentation.from_pretrained(
                "ZhengPeng7/BiRefNet", trust_remote_code=True,
            )
            model.to(device).eval()
            if device.type == "cuda":
                model.half()
            transform = transforms.Compose([
                transforms.Resize((1024, 1024)),
                transforms.ToTensor(),
                transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225]),
            ])
            _bg_cache["model"] = model
            _bg_cache["device"] = device
            _bg_cache["transform"] = transform
            print(f"  BiRefNet loaded on {device}")

        model = _bg_cache["model"]
        device = _bg_cache["device"]
        transform = _bg_cache["transform"]
        img = Image.open(io.BytesIO(image_bytes)).convert("RGB")
        orig_size = img.size
        t = transform(img).unsqueeze(0).to(device)  # type: ignore[union-attr]
        if device.type == "cuda":  # type: ignore[union-attr]
            t = t.half()
        with torch.no_grad():
            preds = model(t)[-1].sigmoid().cpu()  # type: ignore[union-attr]
        mask = transforms.ToPILImage()(preds[0].squeeze())
        mask = mask.resize(orig_size, Image.Resampling.LANCZOS)
        result = img.convert("RGBA")
        result.putalpha(mask)
        buf = io.BytesIO()
        result.save(buf, format="PNG")
        return buf.getvalue()
    except ImportError:
        from rembg import remove
        return remove(image_bytes, alpha_matting=True)


def _crop_and_fit(img: Image.Image, target: int = 512) -> Image.Image:
    bbox = img.getbbox()
    if bbox is None:
        return Image.new("RGBA", (target, target), (0, 0, 0, 0))
    cropped = img.crop(bbox)
    max_ext = int(target * 0.9)
    w, h = cropped.size
    scale = min(max_ext / w, max_ext / h)
    nw, nh = max(1, round(w * scale)), max(1, round(h * scale))
    resized = cropped.resize((nw, nh), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (target, target), (0, 0, 0, 0))
    canvas.paste(resized, ((target - nw) // 2, (target - nh) // 2))
    return canvas


def process_sheet(raw_bytes: bytes, subdir: Path) -> list[str]:
    sheet = Image.open(io.BytesIO(raw_bytes)).convert("RGBA")
    w, h = sheet.size
    cw, ch = w // 2, h // 2
    margin = 4
    paths = []
    for i, (row, col) in enumerate([(0, 0), (0, 1), (1, 0), (1, 1)]):
        frame = sheet.crop((
            col * cw + margin, row * ch + margin,
            (col + 1) * cw - margin, (row + 1) * ch - margin,
        ))
        buf = io.BytesIO()
        frame.save(buf, format="PNG")
        bg_removed = _remove_bg(buf.getvalue())
        processed = Image.open(io.BytesIO(bg_removed)).convert("RGBA")
        processed = _crop_and_fit(processed)
        out_buf = io.BytesIO()
        processed.save(out_buf, format="PNG")
        frame_path = subdir / f"frame_{i + 1}.png"
        frame_path.write_bytes(out_buf.getvalue())
        paths.append(f"{subdir.name}/frame_{i + 1}.png")
    return paths


