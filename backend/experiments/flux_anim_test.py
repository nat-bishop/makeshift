# ── Main ───────────────────────────────────────────────────────────────


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    template_bytes = make_template_2x2()
    (OUTPUT_DIR / "template.png").write_bytes(template_bytes)

    print("FLUX Animation Test")
    print(f"  {len(CHARACTERS)} characters")
    print(f"  Image: FLUX.2 Klein 9B (local, {FLUX_URL})")
    print(f"  Text: {TEXT_MODEL}")
    print(f"  Output: {OUTPUT_DIR}\n")

    t0 = time.time()
    all_results: list[dict] = []

    for char in CHARACTERS:
        print(f"\n{'=' * 50}")
        print(f"  {char['id']} — {char['desc']}")
        print(f"{'=' * 50}")

        subdir = OUTPUT_DIR / char["id"]
        subdir.mkdir(parents=True, exist_ok=True)

        result: dict = {
            "id": char["id"],
            "desc": char["desc"],
            "animation_type": "",
            "cells": {},
            "prompt": "",
            "sheet": "",
            "frames": [],
            "timing_s": 0.0,
            "error": None,
        }
        t1 = time.time()

        try:
            # Step 1: Cell descriptions (Gemini text LLM)
            print("  generating cell descriptions...")
            anim_data = generate_cells(char["desc"])
            result["animation_type"] = anim_data.get("animation_type", "unknown")
            result["cells"] = anim_data.get("cells", {})
            print(f"    type: {result['animation_type']}")

            # Step 2: Build prompt
            prompt = build_prompt(char["appearance"], anim_data)
            result["prompt"] = prompt

            # Step 3: Generate sheet (FLUX)
            print("  generating sheet (FLUX)...")
            raw = generate_sheet(template_bytes, prompt)
            (subdir / "sheet.png").write_bytes(raw)
            result["sheet"] = f"{subdir.name}/sheet.png"

            # Step 4: Process frames
            print("  processing frames...")
            result["frames"] = process_sheet(raw, subdir)
            print("  done")

        except Exception as e:
            result["error"] = f"{type(e).__name__}: {e}"
            print(f"  FAILED: {result['error']}")

        result["timing_s"] = round(time.time() - t1, 2)
        all_results.append(result)

    wall = time.time() - t0

    dashboard = generate_dashboard(all_results)
    (OUTPUT_DIR / "dashboard.html").write_text(dashboard, encoding="utf-8")

    ok = sum(1 for r in all_results if not r["error"])
    print(f"\n{'=' * 60}")
    print(f"DONE in {wall:.0f}s — {ok}/{len(all_results)} succeeded")
    print(f"Dashboard: {OUTPUT_DIR / 'dashboard.html'}")


if __name__ == "__main__":
    main()
